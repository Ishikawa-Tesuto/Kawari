#!/usr/bin/env python3
"""Convert VTube Studio parameter settings into Studio's extended parameter-map format."""
import argparse
import json
import math
from pathlib import Path
import sys


def num(value):
    if isinstance(value, bool) or not isinstance(value, (float, int)) or not math.isfinite(value) or abs(value) > 1e6:
        raise ValueError('invalid number')
    return float(value)


def identifier(value):
    if not isinstance(value, str) or not value or len(value.encode()) > 128 or any(c.isspace() or ord(c)<33 or ord(c)==127 or c=='#' for c in value):
        raise ValueError('invalid parameter ID')
    return value


def convert(config, smoothing_scale=5.0):
    if not 0 <= smoothing_scale <= 50 or not math.isfinite(smoothing_scale):
        raise ValueError('smoothing scale must be 0..50 ms per unit')
    if not isinstance(config,dict) or config.get('Version') != 1 or not isinstance(config.get('ParameterSettings'),list):
        raise ValueError('expected VTube Studio Version 1 with ParameterSettings')
    rows=['# Generated by import-vtube.py; vts extension requires P0.4a',
          '# Input Target InMin InMax OutMin OutMax SmoothMs vts ClampInput ClampOutput',
          f'# Smoothing approximation: {smoothing_scale:g} ms per VTS unit']
    skipped=[]; seen=set(); inputs=set(); count=0
    for i,p in enumerate(config['ParameterSettings'],1):
        try:
            if not isinstance(p,dict): raise ValueError('expected object')
            target=identifier(p.get('OutputLive2D'))
            if p.get('UseBreathing') or p.get('UseBlinking'):
                skipped.append(f'{target}: procedural breathing/blinking (native behavior retained; not imported)'); continue
            if not p.get('Input'):
                skipped.append(f'{target}: no input'); continue
            source=identifier(p['Input'])
            a,b,c,d,s=[num(p[k]) for k in ('InputRangeLower','InputRangeUpper','OutputRangeLower','OutputRangeUpper','Smoothing')]
            if a==b or not 0<=s<=100: raise ValueError('degenerate input range or smoothing outside 0..100')
            if target in seen: raise ValueError('duplicate output parameter')
            flags=[p.get(k,False) for k in ('ClampInput','ClampOutput')]
            if not all(isinstance(v,bool) for v in flags): raise ValueError('invalid clamp flags')
            rows.append(' '.join([source,target,*[format(v,'.9g') for v in (a,b,c,d,s*smoothing_scale)],'vts',*[str(int(v)) for v in flags]]))
            seen.add(target);inputs.add(source);count+=1
        except (KeyError,TypeError,ValueError) as e:
            raise ValueError(f'ParameterSettings row {i}: {e}') from e
    if not count: raise ValueError('no supported parameter mappings')
    return '\n'.join(rows)+'\n',count,len(inputs),skipped


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('config',type=Path);p.add_argument('--output',type=Path,required=True)
    p.add_argument('--smoothing-scale',type=float,default=5.0,help='approximate milliseconds per VTS smoothing unit (default 5)')
    p.add_argument('--force',action='store_true',help='overwrite an existing output map')
    a=p.parse_args()
    try:
        if a.output.resolve()==a.config.resolve(): raise ValueError('output must not overwrite source configuration')
        config=json.loads(a.config.read_text(encoding='utf-8-sig'))
        result,count,inputs,skipped=convert(config,a.smoothing_scale)
        a.output.parent.mkdir(parents=True,exist_ok=True)
        with a.output.open('w' if a.force else 'x',encoding='utf-8') as f: f.write(result)
        print(f'[import] {count} mappings / {inputs} unique inputs -> {a.output}')
        for s in skipped: print('[import] skipped:',s)
        print(f'[import] {len(config.get("Hotkeys",[]))} hotkeys detected; hotkeys, expressions, position, idle and physics settings not imported')
    except (OSError,ValueError,TypeError) as e: p.exit(1,f'[import] {e}\n')

if __name__=='__main__': main()
